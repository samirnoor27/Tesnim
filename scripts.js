const img = (seed, width = 800, height = 450) => {
  if (!seed) return `https://picsum.photos/seed/tasneem/${width}/${height}`;
  
  const str = String(seed).trim();
  
  if (str.startsWith('http://') || str.startsWith('https://')) {
    return str;
  }
  
  if (str.startsWith('photo/') || str.startsWith('./photo/')) {
    return str;
  }
  
  if (str.includes('.')) {
    return `photo/${str}`;
  }
  
  return `https://picsum.photos/seed/${encodeURIComponent(str)}/${width}/${height}`;
};

