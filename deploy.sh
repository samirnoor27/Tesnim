#!/usr/bin/env bash
# ==============================================================================
# سكريبت النشر المباشر بضغطة واحدة لمدونة تسنيم
# الاستخدام: ./deploy.sh "رسالة التحديث"
# ==============================================================================

# إيقاف التنفيذ فورًا عند حدوث أي خطأ
set -e

# تحديد رسالة الالتزام (Commit Message)، والاستعانة بالرسالة الافتراضية "تحديث المحتوى" في حال عدم إدخال نص
MSG="${1:-تحديث المحتوى}"

# 1. تجهيز كافة الملفات المعدلة وتضمينها للرفع (git add)
# 2. إنشاء التزام جديد بالرسالة المحددة (git commit)
# 3. طباعة تنبيه في حال عدم وجود أي تعديلات جديدة على الملفات
git add -A && git commit -m "$MSG" || echo "لا توجد تغييرات جديدة للنشر"

# رفع التغييرات إلى الفرع الرئيسي (main) على المستودع الخاص بك في GitHub
git push origin main

# رسالة تأكيد إتمام عملية الرفع بنجاح
echo "✅ تم الرفع بنجاح! سيظهر التحديث على الموقع خلال دقيقة."
